"""Stage68 real WASM artifact/provenance contract offline regression tests."""
from __future__ import annotations
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT=Path(__file__).resolve().parents[1]
SCRIPT=ROOT/"research"/"htkpa"/"native_compat"/"audit_wasm.py"
spec=importlib.util.spec_from_file_location("_htkpa_stage68_test",SCRIPT)
assert spec and spec.loader
m=importlib.util.module_from_spec(spec)
sys.modules[spec.name]=m
spec.loader.exec_module(m)


class Stage68Tests(unittest.TestCase):
    def fixture(self,dir):
        folder=Path(dir)
        hashes={}
        files={
            "htkpa_native_frac.mjs":b"fake javascript generated by emulator"*100,
            "htkpa_native_frac.wasm":b"fake wasm generated by emulator"*100,
        }
        for name,data in files.items():
            (folder/name).write_bytes(data)
            hashes[name]={"sha256":m.builder.sha(folder/name),"bytes":len(data)}
        (folder/"LICENSE.r8brain.txt").write_text(
            "MIT License\nCopyright (c) 2013-2023 Aleksey Vaneev\n",
            encoding="utf-8")
        config={
            "stage":67,"schema_version":1,
            "public_source_commit":m.stage55.PINS["v6.5"],
            "original_vendor_dll_sha256":
                "fa8b3613a75de69deb49a9e72dce453312e4814a5c99bb6ea2e8a9e80debd5fa",
            "bridge_cpp_sha256":m.builder.sha(m.builder.BRIDGE),
            "consumer_adapter_sha256":m.builder.sha(
                ROOT/"src"/"htkpa_wasm_adapter.js"),
            "public_mit_license_sha256":m.builder.sha(
                folder/"LICENSE.r8brain.txt"),
            "exports":m.builder.EXPORTS,
            "runtime_exports":m.builder.RUNTIME_EXPORTS,
            "vendor_binary_included":False,
            "patch":{"beta_hex":"0x1.91af20df9e8bap+3",
                     "power_hex":"0x1.83fa5ca7f6a99p+0",
                     "interpolation_mode":"forced_poly_673",
                     "phase_positions":673},
            "output":hashes}
        (folder/"htkpa_wasm_build.json").write_text(json.dumps(config),
                                                      encoding="utf-8")
        return config

    def test_exact_source_and_abi_manifest_with_required_heap_exports(self):
        with tempfile.TemporaryDirectory() as d:
            config=self.fixture(d)
            validated=m.verify_build(Path(d))
            self.assertEqual(validated["public_commit"],m.stage55.PINS["v6.5"])
            self.assertEqual(validated["wasm_sha256"],
                             config["output"]["htkpa_native_frac.wasm"]["sha256"])
            self.assertEqual(m.builder.RUNTIME_EXPORTS,["HEAPU8","HEAPF64"])
            self.assertEqual(m.NATIVE_BOUNDS,{"reverse":1e-14,"forward":1e-16})

    def test_reject_tampered_wasm_or_mjs_or_mit_license(self):
        for filename in ("htkpa_native_frac.wasm",
                         "htkpa_native_frac.mjs","LICENSE.r8brain.txt"):
            with self.subTest(file=filename),tempfile.TemporaryDirectory() as d:
                self.fixture(d)
                (Path(d)/filename).write_bytes(b"MODIFIED")
                with self.assertRaises(ValueError):
                    m.verify_build(Path(d))

    def test_reject_wrong_window_patch_and_missing_runtime_export(self):
        for prop,new in (("runtime_exports",["HEAPU8"]),
                         ("public_source_commit","deadbeef"),
                         ("vendor_binary_included",True)):
            with tempfile.TemporaryDirectory() as d:
                data=self.fixture(d)
                data[prop]=new
                (Path(d)/"htkpa_wasm_build.json").write_text(json.dumps(data))
                with self.assertRaises(ValueError):
                    m.verify_build(Path(d))
        with tempfile.TemporaryDirectory() as d:
            data=self.fixture(d)
            data["patch"]["phase_positions"]=1000
            (Path(d)/"htkpa_wasm_build.json").write_text(json.dumps(data))
            with self.assertRaises(ValueError):
                m.verify_build(Path(d))

    def test_real_node_runner_syntax_when_node_available(self):
        self.assertTrue(m.RUNNER.is_file())
        if not shutil.which("node"):
            self.skipTest("Node.js unavailable; real runner requires node")
        proc=subprocess.run(["node","--check",str(m.RUNNER)],
                            capture_output=True,text=True)
        self.assertEqual(proc.returncode,0,proc.stderr)

    def test_stage68_reuses_native_evidence_and_no_retiming(self):
        src=SCRIPT.read_text(encoding="utf-8")
        self.assertIn("stage65.read_extended(args.stage64)",src)
        self.assertIn("stage65.detailed_metrics(native[side],output,count)",src)
        self.assertIn("split_bit_equal",src)
        self.assertNotIn("cross_corr",src)
        self.assertEqual(m.earlier.EXPECTED_NATIVE_COUNTS,
                         {"reverse":114,"forward":1067})


if __name__=="__main__":
    unittest.main()
